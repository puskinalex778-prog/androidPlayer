    fun byId(id: String): DeviceEqProfile? = all.firstOrNull { it.id == id }

    /**
     * Автоматически подбирает профиль по имени подключённого Bluetooth/аудио устройства.
     * Более длинные ключи (например "freebuds 5i") проверяются приоритетнее коротких ("freebuds").
     */
    fun match(deviceName: String?, isSpeaker: Boolean): DeviceEqProfile? {
        if (isSpeaker) return byId("phone_speaker")
        val raw = deviceName?.trim()?.lowercase()?.takeIf { it.isNotBlank() } ?: return null
        var best: DeviceEqProfile? = null
        var bestLen = 0
        for (p in all) {
            for (k in p.matchKeys) {
                if (k.length > bestLen && raw.contains(k)) {
                    best = p
                    bestLen = k.length
                }
            }
        }
        return best
    }
